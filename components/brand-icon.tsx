const BRANDS = {
  anthropic: "anthropic",
  "claude-code": "spark",
  openai: "blossom",
  codex: "blossom",
  gemini: "google",
  perplexity: "perplexity",
} satisfies Record<string, keyof typeof MARKS>

export type BrandId = keyof typeof BRANDS
export const BRAND_IDS = Object.keys(BRANDS) as BrandId[]

const round = (n: number) => Math.round(n * 1e5) / 1e5
function place({ box: [x, y, w, h], fit }: Mark): string {
  const scale = fit / Math.max(w, h)
  return `translate(${round(12 - (x + w / 2) * scale)} ${round(12 - (y + h / 2) * scale)}) scale(${round(scale)})`
}

/**
 * A small square tile holding a brand's mark. `size` is the rendered edge in
 * pixels. Pass `label` only when the name is not printed next to the icon;
 * without it the icon is hidden from assistive tech. An id with no mark gets
 * its initial, or a dot, never somebody's logo.
 */
export function BrandIcon({ brand, size = 20, label, className }: {
  brand: BrandId | (string & {})
  size?: number
  label?: string
  className?: string
}) {
  const mark: Mark | null = Object.hasOwn(BRANDS, brand) ? MARKS[BRANDS[brand as BrandId]] : null
  const initial = mark ? "" : (/[\p{L}\p{N}]/u.exec(label ?? brand)?.[0] ?? "").toUpperCase()
  const a11y = label ? { role: "img" as const, "aria-label": label } : { "aria-hidden": true as const }
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className ? `shrink-0 ${className}` : "shrink-0"}
      data-brand={brand}
      {...a11y}
    >
      <rect x="0.5" y="0.5" width="23" height="23" rx="6" fill="currentColor" fillOpacity="0.05" stroke="currentColor" strokeOpacity="0.16" />
      {mark ? (
        <g transform={place(mark)}>
          {mark.paths.map((p) => <path key={p.d} d={p.d} className={p.fill} />)}
        </g>
      ) : initial ? (
        <text x="12" y="12.5" textAnchor="middle" dominantBaseline="central" fontSize="12" fontWeight="600" fill="currentColor">
          {initial}
        </text>
      ) : (
        <circle cx="12" cy="12" r="2.5" fill="currentColor" fillOpacity="0.55" />
      )}
    </svg>
  )
}

/** One line of small print for any page that shows a third-party mark. */
export function BrandNotice({ className }: { className?: string }) {
  return (
    <p className={className ?? "text-xs text-muted-foreground"}>
      Third-party names and logos belong to their owners. They identify what you connect and do not imply endorsement.
    </p>
  )
}
